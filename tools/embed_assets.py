#!/usr/bin/env python3
"""
Dual-Transport UI Shell - Asset Embedder
Compiles dist/ production assets into C++ byte arrays for zero-port in-memory serving.
"""

import os
import sys
import mimetypes

MIME_MAP = {
    ".html": "text/html; charset=utf-8",
    ".js": "application/javascript; charset=utf-8",
    ".mjs": "application/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".json": "application/json; charset=utf-8",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".jpg": "image/jpeg",
    ".jpeg": "image/jpeg",
    ".ico": "image/x-icon",
    ".ttf": "font/ttf",
    ".woff": "font/woff",
    ".woff2": "font/woff2",
}

def get_mime(filename: str) -> str:
    ext = os.path.splitext(filename)[1].lower()
    return MIME_MAP.get(ext, "application/octet-stream")

def sanitize_ident(name: str) -> str:
    return "".join(c if c.isalnum() else "_" for c in name)

def main():
    root_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    dist_dir = os.path.join(root_dir, "dist")
    out_path = os.path.join(root_dir, "engine", "include", "network", "EmbeddedAssets.hpp")

    os.makedirs(os.path.dirname(out_path), exist_ok=True)

    assets = []
    if os.path.exists(dist_dir):
        for root, _, files in os.walk(dist_dir):
            for file in files:
                abs_p = os.path.join(root, file)
                rel_p = os.path.relpath(abs_p, dist_dir).replace("\\", "/")
                # Map URL paths
                url_path = "/" + rel_p
                assets.append((url_path, abs_p, get_mime(file)))

    print(f"[EMBED] Found {len(assets)} assets to embed into C++ binary...")

    with open(out_path, "w", encoding="utf-8") as out:
        out.write("""// ==============================================================================
// AUTOMATICALLY GENERATED FILE - DO NOT EDIT MANUALLY!
// Generated by tools/embed_assets.py
// Lucid Engine Dual-Transport UI Shell In-Memory Assets
// ==============================================================================

#pragma once

#include <cstdint>
#include <cstddef>
#include <string>
#include <string_view>
#include <unordered_map>

namespace engine::network {

struct EmbeddedAssetEntry {
    const char* path;
    const uint8_t* data;
    size_t size;
    const char* mime;
};

""")
        # Write byte arrays
        for idx, (url_path, file_path, mime) in enumerate(assets):
            var_name = f"g_assetData_{idx}_{sanitize_ident(url_path)}"
            try:
                with open(file_path, "rb") as f:
                    data = f.read()
            except Exception as e:
                print(f"[WARN] Failed to read {file_path}: {e}")
                continue

            out.write(f"// Path: {url_path} ({len(data)} bytes)\n")
            out.write(f"static const uint8_t {var_name}[] = {{\n")
            # Write 24 bytes per line
            for i in range(0, len(data), 24):
                chunk = data[i:i+24]
                line = ", ".join(f"0x{b:02x}" for b in chunk)
                out.write(f"    {line},\n")
            out.write("};\n\n")

        # Write index table
        out.write("static const EmbeddedAssetEntry g_embeddedAssetsTable[] = {\n")
        for idx, (url_path, _, mime) in enumerate(assets):
            var_name = f"g_assetData_{idx}_{sanitize_ident(url_path)}"
            out.write(f'    {{ "{url_path}", {var_name}, sizeof({var_name}), "{mime}" }},\n')
            if url_path == "/index.html":
                # Alias root to index.html
                out.write(f'    {{ "/", {var_name}, sizeof({var_name}), "{mime}" }},\n')
        out.write("};\n\n")

        # Write lookup function
        out.write("""inline bool getEmbeddedAsset(const std::string& reqPath, const uint8_t*& outData, size_t& outSize, const char*& outMime) {
    std::string path = reqPath.empty() ? "/" : reqPath;
    // Strip query parameters
    auto qPos = path.find('?');
    if (qPos != std::string::npos) {
        path = path.substr(0, qPos);
    }
    if (path == "") path = "/";

    for (const auto& entry : g_embeddedAssetsTable) {
        if (path == entry.path) {
            outData = entry.data;
            outSize = entry.size;
            outMime = entry.mime;
            return true;
        }
    }

    // Default fallback to index.html for SPA client-side routing
    for (const auto& entry : g_embeddedAssetsTable) {
        if (std::string(entry.path) == "/" || std::string(entry.path) == "/index.html") {
            outData = entry.data;
            outSize = entry.size;
            outMime = entry.mime;
            return true;
        }
    }

    return false;
}

inline size_t getEmbeddedAssetCount() {
    return sizeof(g_embeddedAssetsTable) / sizeof(g_embeddedAssetsTable[0]);
}

} // namespace engine::network
""")

    print(f"[OK] Successfully embedded assets into: {out_path}")

if __name__ == "__main__":
    main()
